-- Clase 6, bloque 1: el historial que se llena solo.
-- (El bloque 2, la moto en el mapa, no necesita SQL: Broadcast no guarda nada en la base.)

create table public.historial (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null references public.pedidos on delete cascade,
  estado text not null,
  created_at timestamptz not null default now()
);

alter table public.historial enable row level security;

-- La regla de oro otra vez: ves el historial si puedes ver el pedido.
create policy "Ves el historial si puedes ver el pedido"
on public.historial for select to authenticated
using (exists (select 1 from public.pedidos where pedidos.id = historial.pedido_id));

grant select on public.historial to authenticated;

-- El evento: cada que un pedido nace o cambia de estado, la base lo anota sola.
-- Nadie tiene que acordarse: ni el botón de la tienda ni la app del cliente saben que esto existe.
create function public.anotar_en_historial()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' or new.estado is distinct from old.estado then
    insert into public.historial (pedido_id, estado) values (new.id, new.estado);
  end if;
  return new;
end;
$$;

create trigger anotar_en_historial
after insert or update on public.pedidos
for each row execute function public.anotar_en_historial();
