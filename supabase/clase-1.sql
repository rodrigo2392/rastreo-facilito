-- Clase 1: la tabla de pedidos.
-- Pega todo esto en el SQL Editor de tu proyecto de Supabase y dale Run.

create table public.pedidos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  descripcion text not null,
  direccion text not null,
  telefono text not null,
  estado text not null default 'recibido'
);

-- Permisos sobre la tabla: con la llave publishable (rol anon)
-- y, desde la clase 2, con sesión (authenticated).
-- Supabase está dejando de darlo solo (a todos los proyectos desde el 30 de octubre de 2026),
-- así que lo damos a mano.
grant select, insert, update on public.pedidos to anon, authenticated;

-- Sin RLS a propósito: cualquiera con la URL y la llave publishable puede leer
-- y modificar la tabla. Nunca así en producción; en la clase 2 se activa RLS.
alter table public.pedidos disable row level security;

